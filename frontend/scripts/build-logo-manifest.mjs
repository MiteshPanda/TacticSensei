// Scans public/clubs/ and writes src/data/predictor/clubLogos.generated.ts.
// Runs from predev/prebuild and must never fail the build.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const logoDir = join(root, "public", "clubs");
const clubsFile = join(root, "src", "data", "predictor", "clubs.ts");
const outFile = join(root, "src", "data", "predictor", "clubLogos.generated.ts");
const EXT_PRIORITY = [".svg", ".png", ".webp", ".jpg", ".jpeg"];

function main() {
  const clubIds = [...readFileSync(clubsFile, "utf8").matchAll(/\{\s*id:\s*"([^"]+)"/g)].map((m) => m[1]);
  const files = existsSync(logoDir) ? readdirSync(logoDir) : [];
  const byId = new Map();
  const unknown = [];

  for (const file of files) {
    const ext = extname(file).toLowerCase();
    if (!EXT_PRIORITY.includes(ext)) continue;
    const id = basename(file, extname(file));
    if (!clubIds.includes(id)) {
      unknown.push(file);
      continue;
    }
    const current = byId.get(id);
    if (!current || EXT_PRIORITY.indexOf(ext) < EXT_PRIORITY.indexOf(extname(current).toLowerCase())) {
      byId.set(id, file);
    }
  }

  const entries = [...byId.entries()].sort(([a], [b]) => a.localeCompare(b));
  const body = entries.map(([id, file]) => `  "${id}": "/clubs/${file}",`).join("\n");
  const content =
    "// Generated by scripts/build-logo-manifest.mjs. Do not edit by hand.\n" +
    `export const clubLogos: Record<string, string> = {${body ? `\n${body}\n` : ""}};\n`;

  mkdirSync(dirname(outFile), { recursive: true });
  const previous = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (previous !== content) writeFileSync(outFile, content);

  const missing = clubIds.filter((id) => !byId.has(id));
  console.log(`[logos] ${entries.length}/${clubIds.length} clubs have a logo.`);
  if (unknown.length) console.warn(`[logos] Files matching no club id: ${unknown.join(", ")}`);
  if (missing.length) console.warn(`[logos] Clubs with no logo (${missing.length}): ${missing.join(", ")}`);
}

try {
  main();
} catch (err) {
  console.warn(`[logos] Manifest not updated: ${err instanceof Error ? err.message : err}`);
}
